/** Pick a random dark theme — syncs with index.html pre-apply via sessionStorage */
function pickDefaultTheme(): ThemeColors {
  try {
    const name = sessionStorage.getItem('mynigga-random-theme');
    if (name) {
      const t = THEMES[name];
      if (t) return t;
    }
  } catch { /* SSR or restricted storage */ }
  // Fallback: pick fresh random (index.html should've picked first, but just in case)
  const names = Object.keys(THEMES).filter(n => n !== 'light');
  const pick = names[Math.floor(Math.random() * names.length)]!;
  try { sessionStorage.setItem('mynigga-random-theme', pick); } catch { /* */ }
  return THEMES[pick]!;
}

export const DEFAULT_THEME = pickDefaultTheme();
